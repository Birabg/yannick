/**
 * Fills in descriptions, taglines and meta descriptions from scripts/descriptions-data.js.
 *
 *   npm run descriptions
 *
 * Only empty fields are written, so text the owner wrote or edited is never touched, and the script
 * is safe to re-run. Anything it writes is marked as a draft for the owner to approve in /admin.
 * Writes DESCRIPTIONS-REVIEW.md next to the README.
 */
const fs = require('node:fs');
const path = require('node:path');
const { db } = require('../src/db');
const copy = require('./descriptions-data');

const norm = (s) => String(s).trim().toLowerCase();
const words = (s) => s.trim().split(/\s+/).length;
const rows = db.prepare('SELECT * FROM products').all();
const report = [];
const skipped = [];
const problems = [];

for (const c of copy) {
  const row = rows.find((r) => norm(r.brand) === norm(c.brand) && norm(r.name) === norm(c.name));
  if (!row) {
    skipped.push(`${c.brand} ${c.name}: not in the database`);
    continue;
  }
  const n = words(c.description_en);
  if (n < 35 || n > 55) problems.push(`${row.name}: description is ${n} words`);
  if (c.meta_description.length > 155) problems.push(`${row.name}: meta description too long`);
  const tw = words(c.tagline_en);
  if (tw < 4 || tw > 7) problems.push(`${row.name}: tagline is ${tw} words`);

  const set = {};
  // description_en and the older description column count as one field.
  if (!row.description_en && !row.description) {
    set.description_en = c.description_en;
    set.description = c.description_en;
  }
  if (!row.description_am) set.description_am = c.description_am;
  if (!row.tagline_en) set.tagline_en = c.tagline_en;
  if (!row.tagline_am) set.tagline_am = c.tagline_am;
  if (!row.meta_description) set.meta_description = c.meta_description;
  if (set.description_en || set.description_am) set.description_status = 'draft';
  // The notes were left empty on purpose, so the product stays on the "needs details" list.
  const noNotes = !row.top_notes && !row.heart_notes && !row.base_notes;
  if (noNotes && !row.needs_details) set.needs_details = 1;

  const keys = Object.keys(set);
  if (keys.length) {
    db.prepare(
      `UPDATE products SET ${keys.map((k) => `${k} = @${k}`).join(', ')} WHERE id = @id`
    ).run({
      ...set,
      id: row.id,
    });
  }
  report.push({ row, c, wrote: keys.length > 0, noNotes });
}

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const lines = [
  '# Descriptions review',
  '',
  'Generated by `npm run descriptions` from `scripts/descriptions-data.js`. Every text below is a **draft** for the owner to check in `/admin`',
  '(Edit, change anything that is wrong, tick **Approved**). The English and Amharic texts are live on the site while they are drafts.',
  '',
  'The writer knows these fragrances only by the brand and name on the bottle, so the copy describes general character and nothing more. It states no notes,',
  'hours of wear, awards, release years, perfumers or claims about authenticity or sourcing.',
  '',
  '**Confidence** is how sure the writer is that the character described matches the real fragrance: high (well-known, consistent character),',
  'medium (known, but character varies between versions), low (the exact fragrance or version is not certain from the label; check it first).',
  '',
  '| Product | Description (English) | Tagline | Confidence |',
  '| ------- | --------------------- | ------- | ---------- |',
  ...report.map(
    ({ row, c }) =>
      `| ${cell(row.brand)} ${cell(row.name)} | ${cell(c.description_en)} | ${cell(c.tagline_en)} | ${c.confidence} |`
  ),
  '',
  '## Amharic (needs native review)',
  '',
  'Written as natural, conversational Amharic rather than a word-for-word translation. A native speaker should read every line before it is marked reviewed.',
  '',
  '| Product | Description (Amharic) | Tagline (Amharic) |',
  '| ------- | --------------------- | ----------------- |',
  ...report.map(
    ({ row, c }) =>
      `| ${cell(row.brand)} ${cell(row.name)} | ${cell(c.description_am)} | ${cell(c.tagline_am)} |`
  ),
  '',
  '## Search descriptions (meta, at most 155 characters)',
  '',
  ...report.map(
    ({ row, c }) => `- **${row.name}** (${c.meta_description.length}): ${c.meta_description}`
  ),
  '',
  '## Needs owner confirmation',
  '',
  '**Notes left empty.** Top, heart and base notes were not filled for any product: the official notes differ between versions (Eau de Toilette, Eau de Parfum, Parfum, Extrait) and the version is not printed on every photo. These products stay on the "Needs details" list until you add them:',
  '',
  ...report.filter((r) => r.noNotes).map(({ row }) => `- ${row.brand} ${row.name}`),
  '',
  '**Low confidence, check these first:**',
  '',
  ...report.filter((r) => r.c.confidence === 'low').map(({ row }) => `- ${row.brand} ${row.name}`),
  '',
  '**Skipped:** ' + (skipped.length ? '' : 'none. Every product has a readable brand and name.'),
  ...skipped.map((s) => `- ${s}`),
  '',
  '**Not covered by any copy:** ' +
    (rows
      .filter((r) => !report.some((x) => x.row.id === r.id))
      .map((r) => `${r.brand} ${r.name}`)
      .join(', ') || 'nothing, every product in the database was matched.'),
  '',
];
fs.writeFileSync(path.join(__dirname, '..', 'DESCRIPTIONS-REVIEW.md'), lines.join('\n'));

const wrote = report.filter((r) => r.wrote).length;
console.log(
  `Descriptions written for ${wrote} of ${report.length} matched products (others already had text).`
);
if (skipped.length) console.log('Skipped:\n  ' + skipped.join('\n  '));
if (problems.length) console.log('Check:\n  ' + problems.join('\n  '));
